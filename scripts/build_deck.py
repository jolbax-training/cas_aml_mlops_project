from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DECK_DIR = Path("presentation/deck")
MANIFEST = Path("presentation/manifest.json")
DEFAULT_OUTPUT = Path("report/deck.html")
NOTES_OUTPUT_NAME = "deck_notes.html"
REPORT_PAGE = "presentation_report.html"  # generated by add-presentation-report, next to the deck
WORK_LOG_PAGE = "index.html"
REPO_URL = "https://github.com/jolbax-training/cas_aml_mlops_project"

# The approved outline: order, titles, minutes in tenths (integers, so the sum is exact).
OUTLINE = (
    ("title", "Title", 5),
    ("motivation", "Motivation", 10),
    ("problem", "Problem statement", 15),
    ("approach", "Approach overview", 15),
    ("integrity", "Scoring integrity", 15),
    ("reproducibility", "Reproducibility", 15),
    ("budget", "Budget-safe paid calls", 10),
    ("design", "Experiment design", 10),
    ("results", "Results", 15),
    ("traces", "What the traces say", 15),
    ("limits", "Limits and lessons", 10),
    ("takeaways", "Takeaways", 10),
    ("questions", "Questions", 5),
)
TOTAL_TENTHS = 150

LAYOUTS = {"title", "slot", "text", "single", "split", "pair", "links"}
# Rendered width of one figure in px on a 1920px slide; mirrors the cqw widths in deck.css.
FIGURE_WIDTH_PX = {"single": 1440, "split": 1056, "pair": 920}
SLIDE_PX = 1920
CHART_FLOOR_PX = 18
SLIDE_TEXT_FLOOR_PX = 20
BODY_FLOOR_PX = 28
FORBIDDEN_WORDS = re.compile(r"improvement|breakthrough", re.I)
DENIAL = re.compile(r"\bnot an? (?:measured |general |reliable )?(?:claim of )?(?:improvement|breakthrough)", re.I)
REFERENCE = re.compile(r"\{\{(summary|fmt):([^{}]+)\}\}")
BARE_NUMBER = re.compile(r"(?<![A-Za-z0-9_.])\d{2,}(?![A-Za-z0-9_])")
CHF_NUMBER = re.compile(r"CHF\s*\d")
RATIO_NUMBER = re.compile(r"\d\s*/\s*\d")
KEY_LIKE = re.compile(r"sk-[A-Za-z0-9_-]{16,}|Bearer\s+[A-Za-z0-9._-]{16,}")
MAX_BULLETS = 6
MAX_WORDS = 25
SIZE_WARNING_BYTES = 16 * 1024 * 1024


class DeckError(Exception):
    """A source problem; the build stops and the previous output stays untouched."""


def load_work_log(root: Path):
    """The work-log builder, loaded by path, so its SVG validators serve the deck too."""
    path = root / "scripts" / "build_work_log.py"
    spec = importlib.util.spec_from_file_location("_deck_work_log", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["_deck_work_log"] = module
    spec.loader.exec_module(module)
    return module


# --- sources ------------------------------------------------------------------

def read_toml(path: Path) -> dict:
    try:
        with path.open("rb") as handle:
            return tomllib.load(handle)
    except FileNotFoundError:
        raise DeckError(f"{path.name}: file not found ({path})") from None
    except tomllib.TOMLDecodeError as error:
        raise DeckError(f"{path.name}: invalid TOML ({error})") from None


def read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise DeckError(f"{path}: file not found") from None
    except json.JSONDecodeError as error:
        raise DeckError(f"{path}: invalid JSON ({error})") from None


def tenths(minutes: object, where: str) -> int:
    if isinstance(minutes, bool) or not isinstance(minutes, (int, float)):
        raise DeckError(f"{where}: minutes must be a number")
    value = round(minutes * 10)
    if abs(value - minutes * 10) > 1e-6:
        raise DeckError(f"{where}: minutes must be a multiple of 0.1")
    return value


def check_outline(slides: list[dict]) -> list[int]:
    """The approved 13 slides, in order, with the approved titles and minutes."""
    if len(slides) != len(OUTLINE):
        raise DeckError(f"slides.toml: {len(slides)} slides, the approved outline has {len(OUTLINE)}")
    minutes = []
    for number, (slide, (slide_id, title, expected)) in enumerate(zip(slides, OUTLINE), start=1):
        where = f"slide {number}"
        if slide.get("id") != slide_id:
            raise DeckError(f"{where}: id {slide.get('id')!r}, the approved outline has {slide_id!r}")
        if slide.get("title") != title:
            raise DeckError(f"{where}: title {slide.get('title')!r}, the approved outline has {title!r}")
        value = tenths(slide.get("minutes"), where)
        if value != expected:
            raise DeckError(f"{where}: {value / 10} minutes, the approved outline has {expected / 10}")
        if slide.get("layout") not in LAYOUTS:
            raise DeckError(f"{where}: unknown layout {slide.get('layout')!r}")
        minutes.append(value)
    if sum(minutes) != TOTAL_TENTHS:
        raise DeckError(f"minutes sum to {sum(minutes) / 10}, not {TOTAL_TENTHS / 10}")
    return minutes


# --- numbers by reference -----------------------------------------------------

def lookup(summary: dict, path: str, where: str):
    node: object = summary
    for part in path.split("."):
        if isinstance(node, dict) and part in node:
            node = node[part]
        elif isinstance(node, list) and part.isdigit() and int(part) < len(node):
            node = node[int(part)]
        else:
            raise DeckError(f"{where}: summary path {path!r} does not resolve (at {part!r})")
    return node


def as_text(value: object, where: str, path: str) -> str:
    if isinstance(value, list):
        return "; ".join(as_text(item, where, path) for item in value)
    if isinstance(value, (dict, bool)) or value is None:
        raise DeckError(f"{where}: summary path {path!r} is not a plain value")
    return str(value)


def apply_format(name: str, value: object, where: str, path: str, footnotes: list[str] | None) -> str:
    try:
        if name == "int":
            return str(int(value))
        if name == "pct1":
            return f"{Decimal(str(value)) * 100:.1f}%"
        if name == "ratio":
            if not isinstance(value, dict) or "count" not in value or "of" not in value:
                raise DeckError(f"{where}: {path!r} has no count and of for the ratio format")
            return f"{value['count']}/{value['of']}"
        if name == "chf4":
            full = Decimal(str(value))
            text = str(full.quantize(Decimal("0.0001"), rounding=ROUND_HALF_EVEN))
            if footnotes is not None:
                note = f"* Rounded to four decimals from the quoted total {value}."
                if note not in footnotes:
                    footnotes.append(note)
            return text + "*"
    except (InvalidOperation, ValueError, TypeError):
        raise DeckError(f"{where}: {path!r} cannot be formatted as {name}") from None
    raise DeckError(f"{where}: unknown format {name!r} (use int, pct1, ratio or chf4)")


def resolve(text: str, summary: dict, where: str, footnotes: list[str] | None = None) -> str:
    def replace(match: re.Match) -> str:
        kind, body = match.groups()
        if kind == "summary":
            return as_text(lookup(summary, body, where), where, body)
        name, _, path = body.partition(":")
        if not path:
            raise DeckError(f"{where}: reference {{{{fmt:{body}}}}} needs a format and a path")
        return apply_format(name, lookup(summary, path, where), where, path, footnotes)

    return REFERENCE.sub(replace, text)


def lint_numbers(text: str, where: str, allow: set[str]) -> None:
    """Numbers must be references: reject digit runs, CHF amounts and ratios written literally."""
    plain = REFERENCE.sub("", text)
    for match in BARE_NUMBER.finditer(plain):
        if match.group(0) not in allow:
            raise DeckError(f"{where}: literal number {match.group(0)!r}; use a summary reference or the allow-list")
    if CHF_NUMBER.search(plain) or RATIO_NUMBER.search(plain):
        raise DeckError(f"{where}: literal CHF amount or ratio; use a summary reference")


def lint_words(text: str, where: str) -> None:
    if FORBIDDEN_WORDS.search(text):
        raise DeckError(f"{where}: the words improvement and breakthrough are not allowed in the deck's own text")


def check_caption(text: str, where: str) -> None:
    """Evidence captions may name the claim only to deny it."""
    for sentence in re.split(r"(?<=[.;])\s+", text):
        if FORBIDDEN_WORDS.search(sentence) and not DENIAL.search(sentence):
            raise DeckError(f"{where}: caption uses a forbidden word outside a denial: {sentence!r}")


# --- evidence interface -------------------------------------------------------

class Evidence:
    """Manifest entries by id, with the checks every placed item must pass."""

    def __init__(self, root: Path, manifest: dict, work_log) -> None:
        self.root = root
        self.manifest = manifest
        self.work_log = work_log
        self.items: dict[str, tuple[str, dict]] = {}
        for kind in ("figures", "diagrams", "screenshots", "assets"):
            for entry in manifest.get(kind, []):
                self.items[entry["id"]] = (kind, entry)

    def entry(self, item_id: str, where: str) -> tuple[str, dict]:
        if item_id not in self.items:
            raise DeckError(f"{where}: unknown manifest id {item_id!r}")
        kind, entry = self.items[item_id]
        if not str(entry.get("alt", "")).strip():
            raise DeckError(f"{where}: manifest id {item_id!r} has no alt text")
        return kind, entry

    def data_uri(self, entry: dict, kind: str, where: str) -> str:
        path = self.root / entry["path"]
        if not path.is_file():
            raise DeckError(f"{where}: {entry['id']!r} is marked present but {entry['path']} is missing")
        raw = path.read_bytes()
        fmt = entry.get("format", path.suffix.lstrip("."))
        if fmt == "svg":
            text = raw.decode("utf-8")
            if kind == "diagrams" and entry["path"].endswith(".drawio.svg"):
                text = self.work_log.sanitize_drawio_svg(text, entry["id"], entry.get("caption", entry["id"]), entry["alt"])
            else:
                self.work_log.validate_svg(text)
            raw = text.encode("utf-8")
            mime = "image/svg+xml"
        else:
            mime = {"png": "image/png", "jpg": "image/jpeg", "jpeg": "image/jpeg"}.get(fmt)
            if mime is None:
                raise DeckError(f"{where}: unsupported image format {fmt!r}")
        return f"data:{mime};base64,{base64.b64encode(raw).decode('ascii')}"

    def effective_font_px(self, entry: dict, layout: str) -> float | None:
        units = entry.get("min_font_units")
        viewbox = entry.get("viewbox")
        if not units or not viewbox:
            return None
        width_units = float(viewbox.split()[2])
        return units * FIGURE_WIDTH_PX[layout] / width_units


# --- rendering ----------------------------------------------------------------

def esc(text: object) -> str:
    return html.escape(str(text), quote=True)


class Report:
    """What the build noticed: fatal problems raise; these are printed and, with --strict, fatal."""

    def __init__(self) -> None:
        self.unfilled_slots: list[str] = []
        self.pending: list[str] = []
        self.fallbacks: list[str] = []
        self.warnings: list[str] = []
        self.chart_fonts: list[str] = []
        self.diagrams: list[str] = []

    def notices(self) -> list[str]:
        out = [f"unfilled user slot: {item}" for item in self.unfilled_slots]
        out += [f"screenshot pending: {item}" for item in self.pending]
        return out


def render_figure(ctx: "Context", item_id: str, layout: str, slide_id: str) -> str:
    where = f"slide {slide_id}"
    kind, entry = ctx.evidence.entry(item_id, where)
    caption = esc(entry.get("caption", ""))
    if entry.get("caption"):
        check_caption(entry["caption"], f"{where} caption of {item_id}")
    if kind == "screenshots" and entry.get("status") != "present":
        ctx.report.pending.append(item_id)
        return (
            f'<figure role="img" aria-label="{esc(entry["alt"])}"><div class="pending-box">'
            f"<strong>SCREENSHOT PENDING</strong>{esc(item_id)}<br>{caption}</div></figure>"
        )
    uri = ctx.evidence.data_uri(entry, kind, where)
    font = ctx.evidence.effective_font_px(entry, layout)
    if font is not None:
        ctx.report.chart_fonts.append(f"{item_id}: {font:.1f}px at layout {layout}")
        if font < CHART_FLOOR_PX:
            raise DeckError(f"{where}: chart {item_id!r} text is {font:.1f}px at layout {layout}, below {CHART_FLOOR_PX}px")
    elif kind == "diagrams":
        ctx.report.diagrams.append(item_id)
    cap = f"<figcaption>{caption}</figcaption>" if caption else ""
    return f'<figure><img src="{uri}" alt="{esc(entry["alt"])}">{cap}</figure>'


class Context:
    def __init__(self, root: Path, evidence: Evidence, summary: dict, user_text: dict, report: Report,
                 allow: set[str], output_dir: Path) -> None:
        self.root = root
        self.evidence = evidence
        self.summary = summary
        self.user_text = user_text
        self.report = report
        self.allow = allow
        self.output_dir = output_dir


def text_block(ctx: Context, raw: str, where: str, footnotes: list[str] | None) -> str:
    lint_numbers(raw, where, ctx.allow)
    lint_words(REFERENCE.sub("", raw), where)
    return esc(resolve(raw, ctx.summary, where, footnotes))


def word_lint(ctx: Context, bullets: list[str], where: str) -> None:
    if len(bullets) > MAX_BULLETS:
        ctx.report.warnings.append(f"{where}: {len(bullets)} bullets (more than {MAX_BULLETS})")
    for bullet in bullets:
        if len(bullet.split()) > MAX_WORDS:
            ctx.report.warnings.append(f"{where}: a bullet has more than {MAX_WORDS} words")


def slot_html(ctx: Context, name: str, where: str) -> str:
    slot = ctx.user_text.get(name)
    if not isinstance(slot, dict) or "deck" not in slot or not isinstance(slot["deck"], str):
        raise DeckError(f"{where}: presentation/user_text.toml has no [{name}] deck key")
    text = slot["deck"].strip()
    if not text:
        ctx.report.unfilled_slots.append(name)
        return (
            f'<div class="slot-box" role="note"><strong>YOUR TEXT HERE: slot {esc(name)}</strong>'
            f"Write it in presentation/user_text.toml, table [{esc(name)}], key deck. Nothing is drafted for you.</div>"
        )
    paragraphs = "".join(f"<p>{esc(p.strip())}</p>" for p in re.split(r"\n\s*\n", text) if p.strip())
    return f'<div class="slot-text">{paragraphs}</div>'


def link_item(ctx: Context, label: str, relative: str, built: bool) -> str:
    if built:
        return f'<li><a href="{esc(relative)}">{esc(label)}</a> <span class="foot">{esc(relative)}</span></li>'
    ctx.report.fallbacks.append(relative)
    return f'<li class="missing">{esc(label)}: {esc(relative)} (not built)</li>'


def render_slide(ctx: Context, slide: dict, number: int, total: int) -> str:
    slide_id, title, layout = slide["id"], slide["title"], slide["layout"]
    where = f"slide {number} ({slide_id})"
    footnotes: list[str] = []
    bullets = slide.get("bullets", [])
    word_lint(ctx, bullets, where)
    head = f"<h2>{esc(title)}</h2>"
    subtitle = ""
    if slide.get("subtitle"):
        subtitle = f'<p class="subtitle">{text_block(ctx, slide["subtitle"], where, footnotes)}</p>'
    body = ""
    if bullets:
        items = "".join(f"<li>{text_block(ctx, b, where, footnotes)}</li>" for b in bullets)
        body = f'<ul class="body">{items}</ul>'
    figures = [render_figure(ctx, item, layout, slide_id) for item in slide.get("figures", [])]
    inner = ""
    classes = ""
    if layout == "title":
        meta = ctx.evidence.manifest["title"]
        _, logo = ctx.evidence.entry(slide["logo"], where)
        uri = ctx.evidence.data_uri(logo, "assets", where)
        date = meta.get("date")
        date_html = (
            f'<span class="date">{esc(date)}</span>' if date
            else f'<span class="date unset">{esc(meta["date_placeholder"])}</span>'
        )
        head = ""
        inner = (
            f'<img class="logo" src="{uri}" alt="{esc(logo["alt"])}">'
            f"<h1>{esc(meta['headline'])}</h1>"
            f'<p class="who">{esc(meta["author"])}<br>{esc(meta["course"])}</p>{date_html}'
        )
        classes = " title-slide"
    elif layout == "slot":
        inner = slot_html(ctx, slide["slot"], where)
    elif layout == "text":
        inner = subtitle + body
        subtitle = ""
    elif layout == "single":
        inner = f'<div class="stage single">{figures[0]}</div>'
    elif layout == "split":
        inner = f'<div class="stage split"><div class="col-text">{body}</div>{figures[0]}</div>'
        body = ""
    elif layout == "pair":
        inner = f'<div class="stage pair">{"".join(figures)}</div>'
    elif layout == "links":
        report_ok = (ctx.output_dir / REPORT_PAGE).is_file()
        demo = ctx.evidence.manifest["recording"]["built_player"]
        demo_name = Path(demo).name
        items = [
            link_item(ctx, "Printable report", REPORT_PAGE, report_ok),
            link_item(ctx, "Recorded demo player", demo_name, (ctx.output_dir / demo_name).is_file()),
            link_item(ctx, "Work log", WORK_LOG_PAGE, (ctx.output_dir / WORK_LOG_PAGE).is_file()),
            f'<li><a href="{esc(REPO_URL)}">Repository</a> <span class="foot">{esc(REPO_URL)}</span></li>',
        ]
        inner = f'<ul class="links">{"".join(items)}</ul>'
    foot = ""
    if slide.get("footnote"):
        foot = f'<p class="footnote">{text_block(ctx, slide["footnote"], where, footnotes)}</p>'
    elif footnotes:
        foot = ""
    if footnotes:
        foot += "".join(f'<p class="footnote">{esc(note)}</p>' for note in footnotes)
    label = f"Slide {number} of {total}: {title}"
    return (
        f'<section class="slide{classes}" id="s{number}" aria-label="{esc(label)}">'
        f"{head}{subtitle}{inner}{foot}</section>"
    )


def render_notes(ctx: Context, notes: dict, slide: dict, number: int, total: int, running: int) -> tuple[str, str]:
    """The notes of one slide as (panel markup, notes-page markup)."""
    slide_id = slide["id"]
    lines = notes.get(slide_id)
    where = f"notes of {slide_id}"
    if not isinstance(lines, list) or not lines or not all(isinstance(line, str) and line.strip() for line in lines):
        raise DeckError(f"{where}: notes.toml needs a non-empty list of strings")
    paragraphs = "".join(f"<p>{text_block(ctx, line, where, None)}</p>" for line in lines)
    minutes = tenths(slide["minutes"], where)
    header = (
        f"Slide {number} of {total}: {slide['title']} | {minutes / 10:g} min | "
        f"running total {running / 10:g} of {TOTAL_TENTHS / 10:g} min"
    )
    panel = f'<aside class="notes" id="n{number}" aria-label="Speaker notes for slide {number}"><h2>{esc(header)}</h2>{paragraphs}</aside>'
    page = f'<section class="note-page"><h2>{esc(header)}</h2>{paragraphs}</section>'
    return panel, page


NOTES_CSS = """
body{font-family:system-ui,sans-serif;color:#111;background:#fff;margin:24px;font-size:20px;line-height:1.4}
h1{font-size:28px}
.note-page{padding:8px 0 24px;border-bottom:1px solid #999}
.note-page h2{font-size:22px;margin:0 0 8px}
p{margin:0 0 8px}
@page{size:A4;margin:15mm}
@media print{body{margin:0}.note-page{break-after:page;border:0}}
"""


def build(root: Path, output: Path) -> tuple[str, str, Report]:
    deck_dir = root / DECK_DIR
    slides_toml = read_toml(deck_dir / "slides.toml")
    notes = read_toml(deck_dir / "notes.toml")
    css = (deck_dir / "deck.css").read_text(encoding="utf-8")
    script = (deck_dir / "deck.js").read_text(encoding="utf-8")
    manifest = read_json(root / MANIFEST)
    summary = read_json(root / manifest["summary"])
    user_text = read_toml(root / manifest["user_text"]["path"])
    slides = slides_toml.get("slide", [])
    minutes = check_outline(slides)
    allow = {entry["token"] for entry in slides_toml.get("lint", {}).get("allow", []) if entry.get("reason")}
    ctx = Context(root, Evidence(root, manifest, load_work_log(root)), summary, user_text, Report(), allow, output.parent)
    total = len(slides)
    rendered, panels, pages = [], [], []
    running = 0
    for number, slide in enumerate(slides, start=1):
        running += minutes[number - 1]
        rendered.append(render_slide(ctx, slide, number, total))
        panel, page = render_notes(ctx, notes, slide, number, total, running)
        panels.append(panel)
        pages.append(page)
    unknown = set(notes) - {slide["id"] for slide in slides}
    if unknown:
        raise DeckError(f"notes.toml: notes for unknown slide ids {sorted(unknown)}")
    body = "".join(f"{section}{panel}" for section, panel in zip(rendered, panels))
    title = manifest["title"]["headline"]
    deck = (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{esc(title)}</title><style>{css}</style></head><body>"
        f'<main aria-label="Slides">{body}</main>'
        '<div id="counter" aria-live="polite">1 / 13</div>'
        f"<script>{script}</script></body></html>\n"
    )
    notes_page = (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        f"<title>Speaker notes: {esc(title)}</title><style>{NOTES_CSS}</style></head><body>"
        f"<h1>Speaker notes</h1>{''.join(pages)}</body></html>\n"
    )
    validate_output(deck)
    validate_output(notes_page)
    if len(deck.encode("utf-8")) > SIZE_WARNING_BYTES:
        ctx.report.warnings.append("deck.html is larger than 16 MB")
    return deck, notes_page, ctx.report


def validate_output(text: str) -> None:
    if "/Users/" in text or KEY_LIKE.search(text):
        raise DeckError("output contains a home path or a key-like string")
    for pattern in (r"<link\b", r"<iframe\b", r"<script[^>]*\ssrc=", r"<img[^>]*\ssrc=\"(?!data:)", r"url\(\s*['\"]?(?!data:|#)"):
        if re.search(pattern, text, re.I):
            raise DeckError(f"output loads an external resource ({pattern})")
    if re.search(r"<(?:img|source|video|audio|object|embed)[^>]*\s(?:src|data)=\"https?:", text, re.I):
        raise DeckError("output loads an external resource")


def write_pair(root: Path, output: Path, deck: str, notes_page: str) -> None:
    """Write both files atomically (the work-log writer); a failed write keeps the previous file."""
    work_log = load_work_log(root)
    work_log.write_atomic(output, deck)
    work_log.write_atomic(output.parent / NOTES_OUTPUT_NAME, notes_page)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repository root (default: this repository)")
    parser.add_argument("--output", type=Path, default=None, help=f"deck file (default: <root>/{DEFAULT_OUTPUT})")
    parser.add_argument("--check", action="store_true", help="validate and write nothing")
    parser.add_argument("--strict", action="store_true", help="check, and fail on unfilled slots or pending screenshots")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    output = (args.output or root / DEFAULT_OUTPUT).resolve()
    try:
        deck, notes_page, report = build(root, output)
        notices = report.notices()
        if args.strict and notices:
            raise DeckError("strict: " + "; ".join(notices))
        if not (args.check or args.strict):
            write_pair(root, output, deck, notes_page)
    except DeckError as error:
        print(f"build_deck: {error}", file=sys.stderr)
        return 1
    verb = "checked" if (args.check or args.strict) else f"wrote {output} and {output.parent / NOTES_OUTPUT_NAME}"
    print(f"build_deck: {verb}; 13 slides, {TOTAL_TENTHS / 10:g} minutes, deck {len(deck.encode('utf-8')) // 1024} KiB")
    for line in report.chart_fonts:
        print(f"  chart text: {line}")
    for item in report.diagrams:
        print(f"  diagram {item}: legibility is a coordinator check")
    for line in report.notices():
        print(f"  notice: {line}")
    for line in report.fallbacks:
        print(f"  link not built: {line}")
    for line in report.warnings:
        print(f"  warning: {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
