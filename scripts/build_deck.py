#!/usr/bin/env python3
"""Build the offline 15-minute HTML talk from committed sources and the shared evidence.

    .venv/bin/python scripts/build_deck.py             # write report/deck.html and report/deck_notes.html
    .venv/bin/python scripts/build_deck.py --check     # validate, write nothing
    .venv/bin/python scripts/build_deck.py --strict    # --check, and fail on unfilled slots or pending evidence

Sources: presentation/deck/{slides.toml,notes.toml,deck.css,deck.js}, the manifest and summary of
the presentation evidence, and the user's presentation/user_text.toml (read only, never written).
Every number is a reference into presentation/evidence/summary.json. The output needs no server,
network or library; its only script is the navigation in deck.js. Build order: recording player,
report, work log, then the deck, so the links on the last slide find their targets.
"""

