"""Registered draw.io diagrams in the work log: sanitize-and-rebuild, separate from validate_svg."""

import importlib.util
import re
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("build_work_log_diagrams", REPO / "scripts" / "build_work_log.py")
builder = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = builder
spec.loader.exec_module(builder)

BUILD_TIME = "2026-11-01T12:00:00Z"
OLD_SVG = (REPO / "docs" / "work_log_architecture.svg").read_text(encoding="utf-8")
DRAWIO = (REPO / "docs" / "architecture_physical.drawio.svg").read_text(encoding="utf-8")
LOGICAL = (REPO / "docs" / "architecture_logical.drawio.svg").read_text(encoding="utf-8")
ANCHOR = "<defs/>"  # draw.io's empty <defs/>: the mutations below are inserted after it
assert ANCHOR in DRAWIO

DIAGRAM_TOML = """
[[diagram]]
id = "arch-view"
title = "Test view"
svg = "docs/view.drawio.svg"
text = "docs/view.md"
description = "A test diagram."
label = "current"
"""


def make_repo(tmp_path, svg=DRAWIO, diagrams=DIAGRAM_TOML, extra=None):
    root = tmp_path / "repo"
    (root / "docs").mkdir(parents=True)
    files = {
        "docs/one.md": "# One\n\nText.\n",
        "docs/arch.md": "Explains the figure.\n",
        "docs/arch.svg": OLD_SVG,
        "docs/view.drawio.svg": svg,
        "docs/view.md": "# View twin\n\nText equivalent of the view.\n",
    }
    files.update(extra or {})
    for name, content in files.items():
        (root / name).write_text(content, encoding="utf-8")
    (root / "docs" / "work_log.toml").write_text(
        '[architecture]\ndiagram = "docs/arch.svg"\nexplanation = "docs/arch.md"\n'
        + diagrams
        + '\n[[section]]\nid = "one"\ntitle = "Document one"\npath = "docs/one.md"\nlabel = "current"\n',
        encoding="utf-8")
    return root


def build(root, check=False):
    return builder.run(root, root / "docs" / "work_log.toml", root / "report" / "index.html",
                       builder.parse_build_time(BUILD_TIME), check)


def page(root):
    build(root)
    return (root / "report" / "index.html").read_text(encoding="utf-8")


def sanitize(text):
    return builder.sanitize_drawio_svg(text, "x", "Title", "Description")


def with_inserted(fragment):
    return DRAWIO.replace(ANCHOR, ANCHOR + fragment, 1)


# --- sanitizer ----------------------------------------------------------------------

@pytest.mark.parametrize("source", [DRAWIO, LOGICAL])
def test_real_exports_are_accepted_and_rebuilt(source):
    out = sanitize(source)
    root = builder.ET.fromstring(out)
    assert root.get("role") == "img" and root.get("aria-labelledby") == "x-svg-title x-svg-desc"
    ids = {e.get("id") for e in root.iter() if e.get("id")}
    assert ids == {"x-svg-title", "x-svg-desc"}
    # the editable payload, draw.io page styling, and bookkeeping never reach the page
    for text in ("content=", "mxfile", "data-cell-id", "color-scheme", "background", "version=", "xlink", "<!DOCTYPE"):
        assert text not in out, text
    assert re.search(r"<text", out) and "<foreignObject" not in out
    assert not re.search(r"</?ns\d+:", out)


def test_public_doctype_and_comment_are_accepted_but_not_kept():
    assert "<!DOCTYPE" in DRAWIO and "<!--" in DRAWIO  # the real export has both
    out = sanitize(DRAWIO)
    assert "<!--" not in out and "<!DOCTYPE" not in out
    sanitize(DRAWIO.replace("<!-- Do not edit this file with editors other than draw.io -->\n", ""))


@pytest.mark.parametrize("bad, message", [
    (DRAWIO.replace("<svg ", '<!DOCTYPE svg [<!ENTITY x "y">]><svg ', 1), "ENTITY|DOCTYPE"),
    (DRAWIO.replace("<svg ", '<!DOCTYPE svg [<!ELEMENT a ANY>]><svg ', 1), "DOCTYPE"),
    (DRAWIO.replace("<svg ", '<!DOCTYPE svg SYSTEM "http://example.com/a.dtd"><svg ', 1), "DOCTYPE"),
    (DRAWIO.replace("<svg ", DRAWIO.split("\n")[2] + "<svg ", 1), "DOCTYPE"),  # a second DOCTYPE
    (with_inserted("<script>alert(1)</script>"), "script"),
    (with_inserted('<foreignObject width="1" height="1"><div>x</div></foreignObject>'), "foreignObject"),
    (with_inserted('<image href="https://example.com/x.png"/>'), "image"),
    (with_inserted("<switch><g/></switch>"), "switch"),
    (with_inserted('<a href="https://example.com"><g/></a>'), r"element <a>"),
    (with_inserted("<style>g{fill:red}</style>"), "style"),
    (with_inserted('<use href="#x"/>'), "use"),
    (with_inserted("<foo/>"), "foo"),
    (with_inserted('<g xmlns="http://example.com/ns"/>'), "outside the SVG namespace"),
    (with_inserted("<svg><g/></svg>"), "nested"),
    (with_inserted("<g>text</g>"), "text inside"),
    (with_inserted("<text>t<rect/></text>"), "tspan"),
    (with_inserted("<defs><g/></defs>"), "defs"),
    (with_inserted('<rect onclick="x()" x="0" y="0" width="1" height="1"/>'), "onclick"),
    (with_inserted('<rect xlink:href="https://example.com/x" x="0" y="0" width="1" height="1"/>'), "namespaced"),
    (with_inserted('<rect href="data:image/svg+xml;base64,AAAA" x="0" y="0" width="1" height="1"/>'), "href"),
    (with_inserted('<rect id="a" x="0" y="0" width="1" height="1"/>'), "'id'"),
    (with_inserted('<rect fill="url(https://example.com/m)" x="0" y="0" width="1" height="1"/>'), "fill"),
    (with_inserted('<rect fill="javascript:alert(1)" x="0" y="0" width="1" height="1"/>'), "fill"),
    (with_inserted('<rect style="fill: url(#a)" x="0" y="0" width="1" height="1"/>'), "style declaration"),
    (with_inserted('<rect style="behavior: x" x="0" y="0" width="1" height="1"/>'), "style declaration"),
    (with_inserted('<rect data-extra="1" x="0" y="0" width="1" height="1"/>'), "data-extra"),
    (with_inserted('<path d="M 0 0 L url(x)"/>'), "'d'"),
    (DRAWIO.replace("<svg ", '<svg onload="x()" ', 1), "onload"),
    (DRAWIO.replace('<svg xmlns="http://www.w3.org/2000/svg"', "<svg", 1), "namespace"),
    ("<svg", "invalid SVG"),
])
def test_unsafe_or_unknown_content_is_rejected(bad, message):
    with pytest.raises(builder.WorkLogError, match=message):
        sanitize(bad)


def test_the_original_figure_check_is_unchanged():
    builder.validate_svg(OLD_SVG)
    assert builder.SVG_TAGS == {"svg", "title", "desc", "defs", "marker", "path", "g", "rect", "text", "tspan", "style"}
    for bad in (OLD_SVG.replace("<defs>", '<foreignObject width="1" height="1"/><defs>', 1),
                OLD_SVG.replace("<defs>", "<script>x</script><defs>", 1),
                OLD_SVG.replace('<rect class="arch-bg"', '<rect onclick="x()" class="arch-bg"', 1)):
        with pytest.raises(builder.WorkLogError):
            builder.validate_svg(bad)
    # a draw.io export is not accepted by the old gate (and need not be)
    with pytest.raises(builder.WorkLogError):
        builder.validate_svg(DRAWIO)


# --- registration and rendering -----------------------------------------------------------

def test_registered_diagram_appears_after_the_navigation_with_its_twin(tmp_path):
    html = page(make_repo(tmp_path))
    assert html.index('<section id="architecture"') < html.index('<nav id="sections"') < html.index('<section id="arch-view"')
    assert html.index('<section id="arch-view"') < html.index('<section id="one"')
    section = re.search(r'<section id="arch-view".*?</section>', html, re.S).group(0)
    assert 'role="img"' in section and 'aria-labelledby="arch-view-svg-title arch-view-svg-desc"' in section
    assert "Text equivalent of the view." in section and 'tabindex="0"' in section
    assert 'href="#arch-view"' in html
    assert "docs/view.drawio.svg" in html.split('id="provenance"')[1] and "docs/view.md" in html.split('id="provenance"')[1]
    for text in ("mxfile", "data-cell-id", "<foreignObject", "<script", "<img"):
        assert text not in html


def test_a_source_list_without_diagrams_still_builds(tmp_path):
    root = make_repo(tmp_path, diagrams="")
    assert 'id="arch-view"' not in page(root)


def test_unsafe_diagram_fails_with_a_diagnostic_and_keeps_the_previous_output(tmp_path):
    root = make_repo(tmp_path)
    build(root)
    output = root / "report" / "index.html"
    good = output.read_bytes()
    (root / "docs" / "view.drawio.svg").write_text(with_inserted("<script>alert(1)</script>"), encoding="utf-8")
    with pytest.raises(builder.WorkLogError, match=r"view\.drawio\.svg.*script"):
        build(root)
    with pytest.raises(builder.WorkLogError, match=r"view\.drawio\.svg.*script"):
        build(root, check=True)
    assert output.read_bytes() == good


